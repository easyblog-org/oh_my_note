#!/usr/bin/env node

const fs = require('fs');
const path = require('path');
const { MongoClient } = require('mongodb');
const matter = require('gray-matter');
require('dotenv').config();

const ARTICLES_DIR = path.join(__dirname, '..', 'content', 'articles');

const config = {
  mongoUri: process.env.MONGODB_URI || 'mongodb://localhost:27017/oh_my_note',
  dbName: process.env.MONGODB_DB_NAME || 'oh_my_note',
  collectionName: process.env.MONGODB_COLLECTION || 'articles',
  cleanupOrphaned: process.env.CLEANUP_ORPHANED === 'true',
  isCI: process.env.CI === 'true' || process.env.GITHUB_ACTIONS === 'true'
};

function validateConfig() {
  const errors = [];
  const warnings = [];

  if (!config.mongoUri) {
    errors.push('MONGODB_URI 环境变量未设置');
  } else if (config.mongoUri === 'mongodb://localhost:27017/oh_my_note') {
    if (!process.env.CI) {
      warnings.push('使用默认 MongoDB URI (localhost)');
    } else {
      errors.push('MONGODB_URI 环境变量未设置（CI 环境）');
    }
  } else {
    const uriTrimmed = config.mongoUri.trim();
    if (!uriTrimmed.startsWith('mongodb://') && !uriTrimmed.startsWith('mongodb+srv://')) {
      errors.push(`MONGODB_URI 格式无效: 应以 'mongodb://' 或 'mongodb+srv://' 开头`);
      errors.push(`当前值前 30 个字符: "${config.mongoUri.substring(0, 30)}..."`);
      errors.push('常见问题: 值中包含了双引号或额外空格');
    }

    if ((config.mongoUri.startsWith('"') && config.mongoUri.endsWith('"')) ||
      (config.mongoUri.startsWith("'") && config.mongoUri.endsWith("'"))) {
      errors.push('MONGODB_URI 不应包含引号（请移除值两端的引号）');
    }
  }

  if (warnings.length > 0 && !process.env.CI) {
    console.warn('\n⚠️  警告:');
    warnings.forEach(warn => console.warn(`   - ${warn}`));
  }

  if (errors.length > 0) {
    console.error('\n❌ 配置错误:');
    errors.forEach(err => console.error(`   - ${err}`));
    console.error('\n📖 解决方案:');
    console.error('   1. 检查 .env 文件或 GitHub Secrets');
    console.error('   2. 确保 MONGODB_URI 值不包含引号');
    console.error('   3. 正确格式: mongodb+srv://user:pass@host/?options');
    return false;
  }

  return true;
}

function generateDeterministicSlug(fileName) {
  let hash = 0;
  for (let i = 0; i < fileName.length; i++) {
    const char = fileName.charCodeAt(i);
    hash = ((hash << 5) - hash) + char;
    hash = hash & hash;
  }
  return `article_${Math.abs(hash).toString(36)}`;
}

function generateTitleFromFileName(fileName) {
  return fileName
    .replace(/\.md$/, '')
    .replace(/[-_]+/g, ' ')
    .replace(/\w\S*/g, (txt) => txt.charAt(0).toUpperCase() + txt.substr(1).toLowerCase());
}

function getFileInfo(filePath) {
  try {
    const stats = fs.statSync(filePath);
    return {
      createdAt: stats.birthtime,
      modifiedAt: stats.mtime
    };
  } catch (error) {
    return {
      createdAt: new Date(),
      modifiedAt: new Date()
    };
  }
}

async function fetchExistingArticles(client) {
  const db = client.db(config.dbName);
  const collection = db.collection(config.collectionName);

  const articlesMap = new Map();

  try {
    const cursor = collection.find(
      { '_meta.fileName': { $exists: true } },
      { projection: { slug: 1, '_meta.fileName': 1 } }
    );

    for await (const doc of cursor) {
      if (doc._meta && doc._meta.fileName) {
        articlesMap.set(doc._meta.fileName, {
          slug: doc.slug
        });
      }
    }

    console.log(`📚 从数据库加载了 ${articlesMap.size} 篇已有文章的 slug 映射`);
  } catch (error) {
    console.warn('⚠️  无法加载已有文章映射（可能是首次运行）:', error.message);
  }

  return articlesMap;
}

async function readAllArticles(existingArticlesMap = new Map()) {
  const articles = [];
  const isCI = config.isCI;

  if (!fs.existsSync(ARTICLES_DIR)) {
    console.error(`❌ 文章目录不存在: ${ARTICLES_DIR}`);
    return articles;
  }

  if (isCI) {
    console.log(`🤖 检测到 CI 环境，将跳过所有文件写入操作`);
  }

  const files = fs.readdirSync(ARTICLES_DIR).filter(file => file.endsWith('.md'));

  for (const file of files) {
    const filePath = path.join(ARTICLES_DIR, file);
    const fileContent = fs.readFileSync(filePath, 'utf-8');
    const fileInfo = getFileInfo(filePath);

    try {
      const { data, content } = matter(fileContent);

      let slug = data.slug;
      let autoGeneratedSlug = false;

      if (!slug) {
        const existingArticle = existingArticlesMap.get(file);
        if (existingArticle && existingArticle.slug) {
          slug = existingArticle.slug;
          console.log(`♻️  复用已有 slug: ${file} → "${slug}" (来自数据库)`);
        } else if (isCI) {
          slug = generateDeterministicSlug(file);
          autoGeneratedSlug = true;
          console.log(`🔧 CI 环境：使用确定性 slug: ${file} → "${slug}" (基于文件名)`);
          console.warn(`⚠️  警告: 文件 "${file}" 缺少 slug 字段，请在本地运行 "npm run init-meta" 初始化元数据`);
        } else {
          console.warn(`⚠️  警告: 文件 "${file}" 缺少 slug 字段，请先运行 "npm run init-meta" 初始化元数据`);
          continue;
        }
      }

      let date = data.date ? new Date(data.date) : null;
      let autoGeneratedDate = false;

      if (!date || isNaN(date.getTime())) {
        date = fileInfo.modifiedAt;
        autoGeneratedDate = true;
        console.log(`📅 自动生成 date: ${file} → ${date.toISOString().split('T')[0]} (基于文件修改时间)`);
      }

      let title = data.title;
      let autoGeneratedTitle = false;

      if (!title || title.trim() === '') {
        title = generateTitleFromFileName(file);
        autoGeneratedTitle = true;
        console.log(`📝 自动生成 title: ${file} → "${title}"`);
      }

      const article = {
        slug: slug,
        title: title,
        date: date,
        category: data.category || '',
        tags: Array.isArray(data.tags) ? data.tags : [],
        summary: data.summary || '',
        featured: data.featured || false,
        status: data.status || 'published',
        content: content,
        updatedAt: new Date(),
        _meta: {
          fileName: file,
          autoGeneratedSlug: autoGeneratedSlug,
          autoGeneratedDate: autoGeneratedDate,
          autoGeneratedTitle: autoGeneratedTitle,
          fileCreatedAt: fileInfo.createdAt,
          fileModifiedAt: fileInfo.modifiedAt,
          isCIEnvironment: isCI
        }
      };

      articles.push(article);

      const autoFlags = [];
      if (autoGeneratedSlug) autoFlags.push('slug [自动]');
      if (autoGeneratedTitle) autoFlags.push('title [自动]');
      if (autoGeneratedDate) autoFlags.push('date [自动]');

      if (autoFlags.length > 0) {
        console.log(`✅ 已解析: ${file} (${autoFlags.join(', ')})`);
      } else {
        console.log(`✅ 已解析: ${file}`);
      }

    } catch (error) {
      console.error(`❌ 解析失败 ${file}:`, error.message);
    }
  }

  return articles;
}

async function syncToMongoDB() {
  const client = new MongoClient(config.mongoUri, {
    serverSelectionTimeoutMS: 30000,
    connectTimeoutMS: 30000,
    socketTimeoutMS: 45000,
    maxPoolSize: 10,
    minPoolSize: 1
  });

  try {
    console.log(`\n⏳ 正在连接 MongoDB...`);
    await client.connect();
    console.log(`📦 已连接到 MongoDB`);

    const db = client.db(config.dbName);
    const collection = db.collection(config.collectionName);

    await collection.createIndex({ slug: 1 }, { unique: true });
    await collection.createIndex({ status: 1, date: -1 });
    await collection.createIndex({ '_meta.fileName': 1 });

    console.log(`\n🔍 正在查询已有文章...`);
    const existingArticlesMap = await fetchExistingArticles(client);

    const articles = await readAllArticles(existingArticlesMap);

    if (articles.length === 0) {
      console.log('⚠️  没有找到任何文章');
      return;
    }

    let updatedCount = 0;
    let insertedCount = 0;

    for (const article of articles) {
      const { _meta, ...articleData } = article;

      const result = await collection.updateOne(
        { slug: article.slug },
        { $set: articleData },
        { upsert: true }
      );

      if (result.upsertedCount > 0) {
        insertedCount++;
        console.log(`➕ 新增文章: ${article.title} (${article.slug})`);
      } else {
        updatedCount++;
        console.log(`🔄 更新文章: ${article.title} (${article.slug})`);
      }
    }

    if (config.cleanupOrphaned) {
      const currentSlugs = articles.map(a => a.slug);
      const deleteResult = await collection.deleteMany({
        slug: { $nin: currentSlugs }
      });

      if (deleteResult.deletedCount > 0) {
        console.log(`\n🗑️  清理了 ${deleteResult.deletedCount} 篇已删除的文章`);
      }
    }

    console.log('\n========== 同步完成 ==========');
    console.log(`📊 总计处理: ${articles.length} 篇文章`);
    console.log(`➕ 新增: ${insertedCount} 篇`);
    console.log(`🔄 更新: ${updatedCount} 篇`);
    console.log(`📚 数据库: ${config.dbName}.${config.collectionName}`);

  } catch (error) {
    console.error('\n❌ 同步失败:', error.message);
    throw error;
  } finally {
    await client.close();
    console.log('🔒 已断开 MongoDB 连接\n');
  }
}

async function main() {
  console.log('====================================');
  console.log('🚀 开始同步文章到 MongoDB...');
  console.log('====================================');

  if (config.isCI) {
    console.log('🔄 运行环境: GitHub Actions CI (只读模式)');
  } else {
    console.log('🖥️  运行环境: 本地开发环境');
  }

  if (!validateConfig()) {
    process.exit(1);
  }

  console.log(`\n📋 配置信息:`);
  console.log(`   数据库: ${config.dbName}`);
  console.log(`   集合: ${config.collectionName}`);
  console.log(`   清理孤立文档: ${config.cleanupOrphaned ? '是' : '否'}`);
  console.log('');

  const startTime = Date.now();

  try {
    console.log(`\n📝 开始处理文章...\n`);
    await syncToMongoDB();

    const duration = ((Date.now() - startTime) / 1000).toFixed(2);
    console.log(`⏱️  总耗时: ${duration} 秒`);

  } catch (error) {
    console.error('\n💥 执行出错:', error);
    process.exit(1);
  }
}

main();